// Имена сравниваются без дефисов, пробелов и номера омонима, а учебные записи вариантов
// сводятся к форме каталога: «-(으)ㄹ 수 있다» = «-을 수 있다», «-아/어 보다» = «-어 보다».
// Общий модуль: им пользуются и сервер, и скрипты подготовки TOPIK.
export function normalizeConstruction(name: string): string {
  return name
    .replace(/[\s\-~–—()]/g, "")
    .replace(/\d+$/, "")
    .replace(/았\/었/g, "었")
    .replace(/아\/어/g, "어")
    .replace(/으ㄹ|ㄹ\/을|^ㄹ/g, "을")
    .replace(/으ㄴ|ㄴ\/은|^ㄴ/g, "은");
}
