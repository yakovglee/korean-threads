/** Стабильный номер цвета аватара по нику (8 пар в DESIGN.md) */
export function avatarIndex(nick: string): number {
  let h = 0;
  for (const ch of nick) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return h % 8;
}

/**
 * Инициалы аватара. У корейского имени из трёх и более слогов берётся само имя без фамилии
 * (한서윤 → 서윤): «한서» читается как оборванное имя. Двухсложное имя целиком, иначе первые два символа.
 */
export function initials(author: string): string {
  const chars = Array.from(author);
  return /^[가-힣]{3,}$/.test(author) ? chars.slice(-2).join("") : chars.slice(0, 2).join("");
}

/** Дефис и косая черта перед хангылем не отрываются от суффикса: «-아서/어서» не делится между строк */
export function keepSuffix(text: string): string {
  return text.replace(/([-/])(?=[가-힣])/g, "$1⁠");
}
