export type Part = {
  /** Как слово или окончание показывается в шторке */
  form: string;
  pos?: string;
  ru: string;
  note?: string;
  example?: { ko: string; ru: string };
  /** Нет словарного значения: показывается бейдж «ИИ» (П-9, П-20) */
  ai?: boolean;
};

export type Paragraph =
  | { kind: "ko"; text: string }
  | { kind: "ru"; text: string };

export type Post = {
  id: string;
  author: string;
  nick: string;
  when: string;
  /** Короткая реплика (Threads) или длинный разбор (Substack) */
  variant: "short" | "article";
  title?: string;
  paragraphs: Paragraph[];
  /** Подпись «источник: …» у постов с опорой на книги (П-40) */
  source?: string;
};

export type ThreadItem = {
  type: "thread";
  id: string;
  origin: "bank" | "chat";
  posts: Post[];
};

export type QuizItem = {
  type: "quiz";
  id: string;
  /** «в стиле TOPIK» или без подписи (пропуск из поста) */
  label?: string;
  /** Пропуск обозначен тремя подчёркиваниями */
  stem: string;
  options: string[];
  answer: number;
};

export type FeedItem = ThreadItem | QuizItem;

